-- [컬럼 차이 요약]
-- 구 DB USER_NAME: NULL (암호화) → USER_ID로 대체
-- 구 DB SINGLE_ID → 신 DB KNOX_ID
-- ACTIVE_FLAG / EXTERNAL_USER_FLAG / PRIVACY_POLICY / DELETED: numeric → bit
-- 신 DB 전용: KNOX_ID(←SINGLE_ID), EU_GDPR_POLICY, LOGIN_ERROR_COUNT, TIME_ZONE_ID,
--             LAST_PW_CHANGE_DATETIME, SERVER_LOCATION, JWT, LAST_ACTIVITY_TIME → 기본값
