SELECT 'ESC_DATA_GBM_LINE'        AS 테이블, COUNT(*) AS 건수 FROM ESC_DATA_GBM_LINE
UNION ALL SELECT 'ESC_DATA_EQUIPMENT',      COUNT(*) FROM ESC_DATA_EQUIPMENT
UNION ALL SELECT 'ESC_EQP_MAP',             COUNT(*) FROM ESC_EQP_MAP
UNION ALL SELECT 'ESC_EQP_MAP_ATTACH',      COUNT(*) FROM ESC_EQP_MAP_ATTACH
UNION ALL SELECT 'ESC_EQP_MAP_FILE',        COUNT(*) FROM ESC_EQP_MAP_FILE
UNION ALL SELECT 'ESC_EQP_SAVE_LIST',       COUNT(*) FROM ESC_EQP_SAVE_LIST
UNION ALL SELECT 'ESC_EQP_SCHEDULE',        COUNT(*) FROM ESC_EQP_SCHEDULE
UNION ALL SELECT 'ESC_EQP_SCHEDULE_LIST',   COUNT(*) FROM ESC_EQP_SCHEDULE_LIST
UNION ALL SELECT 'ESC_EQP_SCHEDULE_HISTORY',COUNT(*) FROM ESC_EQP_SCHEDULE_HISTORY
UNION ALL SELECT 'ESC_FAB_ETC_DEVICE_CHECK',COUNT(*) FROM ESC_FAB_ETC_DEVICE_CHECK;
