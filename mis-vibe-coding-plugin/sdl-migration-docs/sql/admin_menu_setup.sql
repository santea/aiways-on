    (SYS_RESOURCE_ID, UPPER_SYS_RESOURCE_ID, SYS_ID, SYS_RESOURCE_NAME, SYS_RESOURCE_TYPE_CODE_ID,
     DELETE_YN, FIRST_REG_DATETIME, FIRST_REGR_ID, LAST_MOD_DATETIME, LAST_MODR_ID)
    VALUES
    ('PORTAL_MENU_CONTENT_MGMT', 'PORTAL_MENU_ADMIN', @SYS_ID, '포탈 컨텐츠 관리', 'MENU',
     '0', GETDATE(), 'admin', GETDATE(), 'admin')
    PRINT 'PORTAL_MENU_CONTENT_MGMT SYS_RESOURCE 등록'
END
ELSE PRINT 'PORTAL_MENU_CONTENT_MGMT 이미 존재'

-- 공지사항 3depth
IF NOT EXISTS (SELECT 1 FROM TN_CF_SYS_RESOURCE WHERE SYS_RESOURCE_ID = 'PORTAL_MENU_ADMIN_NOTICE')
BEGIN
    INSERT INTO TN_CF_SYS_RESOURCE
    (SYS_RESOURCE_ID, UPPER_SYS_RESOURCE_ID, SYS_ID, SYS_RESOURCE_NAME, SYS_RESOURCE_TYPE_CODE_ID,
     DELETE_YN, FIRST_REG_DATETIME, FIRST_REGR_ID, LAST_MOD_DATETIME, LAST_MODR_ID)
    VALUES
    ('PORTAL_MENU_ADMIN_NOTICE', 'PORTAL_MENU_CONTENT_MGMT', @SYS_ID, '공지사항', 'MENU',
     '0', GETDATE(), 'admin', GETDATE(), 'admin')
    PRINT 'PORTAL_MENU_ADMIN_NOTICE SYS_RESOURCE 등록'
END
ELSE PRINT 'PORTAL_MENU_ADMIN_NOTICE 이미 존재'

-- =============================================
-- 3. MENU 등록
-- =============================================

-- 관리기능 1depth
IF NOT EXISTS (SELECT 1 FROM TN_CF_MENU WHERE MENU_ID = 'PORTAL_MENU_ADMIN')
BEGIN
    INSERT INTO TN_CF_MENU
    (MENU_ID, LABEL, LABEL_JSON, MENU_SEQUENCE, MENU_LEVEL,
     USE_YN, DELETE_YN, MENU_TYPE_CODE_ID, EXTERNAL_URL_USE_YN, EXTERNAL_URL)
    VALUES
    ('PORTAL_MENU_ADMIN', '관리기능', '{"ko":"관리기능","en":"Admin"}', 99, 1,
     '1', '0', @MENU_TYPE_CODE_ID, '0', NULL)
    PRINT 'PORTAL_MENU_ADMIN MENU 등록'
END
ELSE
BEGIN
    UPDATE TN_CF_MENU
    SET LABEL = '관리기능', USE_YN = '1', DELETE_YN = '0', MENU_SEQUENCE = 99
    WHERE MENU_ID = 'PORTAL_MENU_ADMIN'
    PRINT 'PORTAL_MENU_ADMIN MENU 업데이트'
END

