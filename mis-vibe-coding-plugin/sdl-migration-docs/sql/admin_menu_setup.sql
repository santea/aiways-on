-- =============================================
-- 관리기능 메뉴 구조 생성
-- 구조:
--   관리기능 (1depth, PORTAL_MENU_ADMIN)
--     └ 포탈 컨텐츠 관리 (2depth, PORTAL_MENU_CONTENT_MGMT)
--         └ 공지사항 (3depth, PORTAL_MENU_ADMIN_NOTICE)
-- =============================================

DECLARE @SYS_ID NVARCHAR(50);
DECLARE @WORKGROUP_ID NVARCHAR(50);
DECLARE @MENU_TYPE_CODE_ID NVARCHAR(50);

SELECT TOP 1 @SYS_ID = SYS_ID FROM TN_CF_SYS;
SELECT @WORKGROUP_ID = WORKGROUP_ID FROM TN_CF_WORKGROUP WHERE WORKGROUP_NAME = 'USER_AUTH_MENU';
SELECT TOP 1 @MENU_TYPE_CODE_ID = CODE_ID FROM TC_CF_COMM_CODE WHERE CODE_ID LIKE 'MENU_TYPE%' AND DELETE_YN = '0';

-- =============================================
-- 1. 기존 PORTAL_MENU_NOTICE_WRITE 메뉴 정리
--    (공지사항 관리 메뉴를 새 구조로 이동하므로 비활성화)
-- =============================================
UPDATE TN_CF_MENU SET USE_YN = '0' WHERE MENU_ID = 'PORTAL_MENU_NOTICE_WRITE';

-- =============================================
-- 2. SYS_RESOURCE 등록
-- =============================================

-- 관리기능 1depth
IF NOT EXISTS (SELECT 1 FROM TN_CF_SYS_RESOURCE WHERE SYS_RESOURCE_ID = 'PORTAL_MENU_ADMIN')
BEGIN
    INSERT INTO TN_CF_SYS_RESOURCE
    (SYS_RESOURCE_ID, UPPER_SYS_RESOURCE_ID, SYS_ID, SYS_RESOURCE_NAME, SYS_RESOURCE_TYPE_CODE_ID,
     DELETE_YN, FIRST_REG_DATETIME, FIRST_REGR_ID, LAST_MOD_DATETIME, LAST_MODR_ID)
    VALUES
    ('PORTAL_MENU_ADMIN', 'PORTAL_MENU_ROOT', @SYS_ID, '관리기능', 'MENU',
     '0', GETDATE(), 'admin', GETDATE(), 'admin')
    PRINT 'PORTAL_MENU_ADMIN SYS_RESOURCE 등록'
END
ELSE PRINT 'PORTAL_MENU_ADMIN 이미 존재'

-- 포탈 컨텐츠 관리 2depth
IF NOT EXISTS (SELECT 1 FROM TN_CF_SYS_RESOURCE WHERE SYS_RESOURCE_ID = 'PORTAL_MENU_CONTENT_MGMT')
BEGIN
