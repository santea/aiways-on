-- 6. 확인
-- =============================================
SELECT M.MENU_ID, M.LABEL, M.MENU_LEVEL, M.MENU_SEQUENCE, M.USE_YN
FROM   TN_CF_MENU M
WHERE  M.MENU_ID LIKE 'PORTAL_MENU_%'
  AND  M.MENU_LEVEL = 1
  AND  M.DELETE_YN = '0'
ORDER BY M.MENU_SEQUENCE;
