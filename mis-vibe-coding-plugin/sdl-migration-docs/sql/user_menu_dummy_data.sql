SELECT M.MENU_ID, SR.UPPER_SYS_RESOURCE_ID, M.LABEL, M.MENU_LEVEL,
       M.MENU_SEQUENCE, M.USE_YN, M.EXTERNAL_URL_USE_YN, M.EXTERNAL_URL
