DECLARE @SYS_ID NVARCHAR(50);
DECLARE @USER_AUTH_MENU_WORKGROUP_ID NVARCHAR(50);
DECLARE @MENU_TYPE_CODE_ID NVARCHAR(50);

SELECT TOP 1 @SYS_ID = SYS_ID FROM TN_CF_SYS;
SELECT @USER_AUTH_MENU_WORKGROUP_ID = WORKGROUP_ID FROM TN_CF_WORKGROUP WHERE WORKGROUP_NAME = 'USER_AUTH_MENU';
SELECT TOP 1 @MENU_TYPE_CODE_ID = CODE_ID FROM TC_CF_COMM_CODE WHERE CODE_ID LIKE 'MENU_TYPE%' AND DELETE_YN = '0';

PRINT '사용할 SYS_ID: ' + ISNULL(@SYS_ID, 'NULL');
PRINT '사용할 WORKGROUP_ID: ' + ISNULL(@USER_AUTH_MENU_WORKGROUP_ID, 'NULL');

IF @SYS_ID IS NULL
BEGIN
    RAISERROR('SYS_ID를 찾을 수 없습니다.', 16, 1); RETURN;
END
IF @USER_AUTH_MENU_WORKGROUP_ID IS NULL
BEGIN
    RAISERROR('USER_AUTH_MENU 워크그룹을 찾을 수 없습니다.', 16, 1); RETURN;
END

-- =============================================
-- 1. TN_CF_SYS_RESOURCE 등록
-- 구 소스: TSMP_MENU (MENU_ID=PORTAL_USER_MGMT)
-- =============================================

-- 사용자 관리 1depth 메뉴 리소스
IF NOT EXISTS (SELECT 1 FROM TN_CF_SYS_RESOURCE WHERE SYS_RESOURCE_ID = 'PORTAL_MENU_USER_MGMT')
BEGIN
    INSERT INTO TN_CF_SYS_RESOURCE
    (SYS_RESOURCE_ID, UPPER_SYS_RESOURCE_ID, SYS_ID, SYS_RESOURCE_NAME, SYS_RESOURCE_TYPE_CODE_ID,
     DELETE_YN, FIRST_REG_DATETIME, FIRST_REGR_ID, LAST_MOD_DATETIME, LAST_MODR_ID)
    VALUES
    ('PORTAL_MENU_USER_MGMT', 'PORTAL_MENU_ROOT', @SYS_ID, '사용자 관리 메뉴', 'MENU',
     '0', GETDATE(), 'admin', GETDATE(), 'admin')
    PRINT 'PORTAL_MENU_USER_MGMT SYS_RESOURCE 등록 완료'
END
ELSE
    PRINT 'PORTAL_MENU_USER_MGMT SYS_RESOURCE 이미 존재'

