-- =============================================
-- 2. TN_CF_MENU 등록
-- 변경: 구 소스 URL /portal/user/listPortalUsers.do → /portal/users (Vue 라우트 경로)
-- EXTERNAL_URL_USE_YN='0' + EXTERNAL_URL에 내부 라우트 경로 저장 → navigateMenu에서 router.push()로 처리
-- =============================================

-- 사용자 관리 1depth
IF NOT EXISTS (SELECT 1 FROM TN_CF_MENU WHERE MENU_ID = 'PORTAL_MENU_USER_MGMT')
BEGIN
    INSERT INTO TN_CF_MENU
    (MENU_ID, LABEL, LABEL_JSON, MENU_SEQUENCE, MENU_LEVEL,
     USE_YN, DELETE_YN, MENU_TYPE_CODE_ID, EXTERNAL_URL_USE_YN, EXTERNAL_URL)
    VALUES
    ('PORTAL_MENU_USER_MGMT', '사용자관리', '{"ko":"사용자관리","en":"User Management"}', 10, 1,
     '1', '0', @MENU_TYPE_CODE_ID, '0', '/portal/users')
    PRINT 'PORTAL_MENU_USER_MGMT MENU 등록 완료'
END
ELSE
BEGIN
    UPDATE TN_CF_MENU
    SET    LABEL = '사용자관리',
           LABEL_JSON = '{"ko":"사용자관리","en":"User Management"}',
           MENU_SEQUENCE = 10, MENU_LEVEL = 1, USE_YN = '1',
           EXTERNAL_URL_USE_YN = '0', EXTERNAL_URL = '/portal/users'
    WHERE  MENU_ID = 'PORTAL_MENU_USER_MGMT'
    PRINT 'PORTAL_MENU_USER_MGMT MENU 업데이트 완료'
END

